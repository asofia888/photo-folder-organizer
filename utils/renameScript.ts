// Generates the rename script users run next to their photo folders.
// Folder names come from the file system and from free-text input, so every
// name is quoted for the target shell and checked again here: the script runs
// against the user's real files.

import { createValidFolderName } from './typeGuards';

export type ScriptPlatform = 'windows' | 'posix';

export interface RenameOperation {
  readonly from: string;
  readonly to: string;
}

export interface RenameScript {
  readonly content: string;
  readonly filename: string;
}

export const detectScriptPlatform = (): ScriptPlatform => {
  if (typeof navigator === 'undefined') return 'posix';
  const nav = navigator as Navigator & { userAgentData?: { platform?: string } };
  const platform = nav.userAgentData?.platform || nav.platform || '';
  return /^win/i.test(platform) ? 'windows' : 'posix';
};

// POSIX sh: single quotes disable every expansion ($, `, \, !). A literal
// single quote is written as '\'' (close quote, escaped quote, reopen).
export const quotePosix = (value: string): string => `'${value.replace(/'/g, `'\\''`)}'`;

// cmd.exe: inside double quotes & | < > ^ ( ) are literal, but %VAR% is still
// expanded in batch files, so % is doubled. A double quote or a line break
// cannot be represented inside a quoted argument; such names (impossible on
// Windows itself) are reported by isBatchSafe instead.
export const quoteBatch = (value: string): string => `"${value.replace(/%/g, '%%')}"`;

// eslint-disable-next-line no-control-regex
const isBatchSafe = (value: string): boolean => !/["\x00-\x1f]/.test(value);

const isSafeTarget = (operation: RenameOperation): boolean =>
  createValidFolderName(operation.to) !== null;

const createPosixScript = (operations: readonly RenameOperation[]): string => {
  const lines = [
    '#!/bin/sh',
    '# Generated by Photo Folder Organizer.',
    '# Renames the folders that sit next to this script. Folders that are',
    '# missing, or whose new name is already taken, are skipped.',
    'cd "$(dirname "$0")" || exit 1',
    '',
    'rename_folder() {',
    '  if [ ! -d "$1" ]; then',
    "    printf 'Skipped (not found): %s\\n' \"$1\"",
    '  elif [ -e "$2" ]; then',
    "    printf 'Skipped (already exists): %s\\n' \"$2\"",
    '  else',
    "    mv -- \"$1\" \"$2\" && printf 'Renamed: %s -> %s\\n' \"$1\" \"$2\"",
    '  fi',
    '}',
    '',
  ];

  for (const operation of operations) {
    if (!isSafeTarget(operation)) {
      lines.push(`printf '%s\\n' ${quotePosix(`Skipped (invalid new name): ${operation.from}`)}`);
      continue;
    }
    lines.push(`rename_folder ${quotePosix(operation.from)} ${quotePosix(operation.to)}`);
  }

  return `${lines.join('\n')}\n`;
};

const createBatchScript = (operations: readonly RenameOperation[]): string => {
  const lines = [
    '@echo off',
    'chcp 65001 > nul',
    'setlocal DisableDelayedExpansion',
    'rem Generated by Photo Folder Organizer.',
    'rem Renames the folders that sit next to this script. Folders that are',
    'rem missing, or whose new name is already taken, are skipped.',
    // pushd (unlike cd) also works when the folder is on a network share.
    'pushd "%~dp0"',
    '',
  ];

  for (const operation of operations) {
    if (!isSafeTarget(operation) || !isBatchSafe(operation.from)) {
      lines.push('echo Skipped one folder: its name cannot be used in a Windows batch file.');
      continue;
    }
    const from = quoteBatch(operation.from);
    const to = quoteBatch(operation.to);
    lines.push(`if not exist ${from} echo Skipped (not found): ${from}`);
    lines.push(`if exist ${from} if exist ${to} echo Skipped (already exists): ${to}`);
    lines.push(`if exist ${from} if not exist ${to} ren ${from} ${to}`);
  }

  lines.push('', 'popd', 'echo.', 'echo Done.', 'pause');
  return `${lines.join('\r\n')}\r\n`;
};

export const createRenameScript = (
  operations: readonly RenameOperation[],
  platform: ScriptPlatform
): RenameScript =>
  platform === 'windows'
    ? { content: createBatchScript(operations), filename: 'rename_folders.bat' }
    : { content: createPosixScript(operations), filename: 'rename_folders.sh' };
